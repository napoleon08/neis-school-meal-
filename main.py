def 한국_오늘():

    현재시간 = datetime.datetime.now(
        datetime.timezone.utc
    )

    한국시간 = 현재시간 + datetime.timedelta(
        hours=9
    )

    return 한국시간.date()


# =========================================================
# 칼로리 추출
# =========================================================

def 칼로리_추출(칼로리정보):

    if not isinstance(
        칼로리정보,
        str
    ):
        return None

    결과 = re.search(
        r"[\d.]+",
        칼로리정보
    )

    if 결과:
        return float(
            결과.group()
        )

    return None


# =========================================================
# 메뉴 분리
# =========================================================

def 메뉴_분리(전체메뉴):

    if not isinstance(
        전체메뉴,
        str
    ):
        return []

    메뉴목록 = 전체메뉴.split(
        "<br/>"
    )

    return [
        메뉴.strip()
        for 메뉴 in 메뉴목록
        if 메뉴.strip()
    ]


# =========================================================
# 급식 API
# =========================================================

@st.cache_data(ttl=600)
def 급식_가져오기(
    교육청코드,
    학교코드,
    날짜
):

    매개변수 = {
        "Type": "json",
        "ATPT_OFCDC_SC_CODE": 교육청코드,
        "SD_SCHUL_CODE": 학교코드,
        "MMEAL_SC_CODE": 2,
        "MLSV_FROM_YMD": 날짜,
        "MLSV_TO_YMD": 날짜
    }

    try:

        응답 = requests.get(
            급식_API,
            params=매개변수,
            timeout=15
        )

        응답.raise_for_status()

        데이터 = 응답.json()

    except requests.exceptions.RequestException:

        return None, "연결오류"

    except ValueError:

        return None, "응답오류"


    # -----------------------------------------------------
    # 정상적인 급식 데이터
    # -----------------------------------------------------

    try:

        행 = 데이터[
            "mealServiceDietInfo"
        ][1]["row"]

        return (
            pd.DataFrame(행),
            "정상"
        )

    except (
        KeyError,
        IndexError,
        TypeError
    ):

        pass


    # -----------------------------------------------------
    # 데이터 없음
    # -----------------------------------------------------

    try:

        결과코드 = 데이터[
            "RESULT"
        ]["CODE"]

        if 결과코드 == "INFO-200":

            return (
                pd.DataFrame(),
                "없음"
            )

    except (
        KeyError,
        TypeError
    ):

        pass


    return (
        pd.DataFrame(),
        "없음"
    )


