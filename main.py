# =========================================================
# NEIS 설정
# =========================================================

NEIS_URL = "https://open.neis.go.kr/hub/mealServiceDietInfo"
교육청코드 = "J10"


# =========================================================
# API KEY 가져오기
# =========================================================

def API키_가져오기():

    try:
        key = st.secrets["NEIS_API_KEY"]

        if key:
            return str(key).strip()

    except Exception:
        pass

    return ""


# =========================================================
# 학교 검색
# =========================================================

def 학교검색(검색어):

    검색어 = 검색어.strip().lower()

    if 검색어 == "":
        return 평택학교

    결과 = []

    for 학교 in 평택학교:

        학교명 = 학교["학교명"].lower()

        if 검색어 in 학교명:
            결과.append(학교)

    return 결과


# =========================================================
# 날짜를 YYYYMMDD로 변환
# =========================================================

def 날짜변환(날짜):

    return 날짜.strftime("%Y%m%d")


# =========================================================
# 알레르기 번호 제거
# =========================================================

def 알레르기번호_제거(메뉴):

    return re.sub(r"\s*\([0-9., ]+\)", "", 메뉴).strip()


# =========================================================
# 급식 데이터 가져오기
# =========================================================

def 급식가져오기(학교코드, 날짜):

    api_key = API키_가져오기()

    params = {
        "Type": "json",
        "ATPT_OFCDC_SC_CODE": 교육청코드,
        "SD_SCHUL_CODE": 학교코드,
        "MMEAL_SC_CODE": "2",
        "MLSV_FROM_YMD": 날짜변환(날짜),
        "MLSV_TO_YMD": 날짜변환(날짜),
        "pIndex": "1",
        "pSize": "100"
    }

    # API KEY가 있으면 사용
    if api_key:
        params["KEY"] = api_key

    try:

        response = requests.get(
            NEIS_URL,
            params=params,
            timeout=15
        )

        response.raise_for_status()

        data = response.json()

    except requests.exceptions.Timeout:

        return {
            "상태": "오류",
            "메시지": "나이스 서버 응답 시간이 초과되었습니다."
        }

    except requests.exceptions.RequestException as e:

        return {
            "상태": "오류",
            "메시지": "나이스 서버에 연결할 수 없습니다."
        }

    except ValueError:

        return {
            "상태": "오류",
            "메시지": "나이스에서 올바른 데이터를 받지 못했습니다."
        }


    # -----------------------------------------------------
    # NEIS 에러 메시지 확인
    # -----------------------------------------------------

    if "RESULT" in data:

        result = data["RESULT"]

        code = result.get("CODE", "")
        message = result.get("MESSAGE", "")

        if code == "INFO-200":

            return {
                "상태": "없음",
                "메시지": "선택한 날짜에는 등록된 급식이 없습니다."
            }

        return {
            "상태": "오류",
            "메시지": f"나이스 API 오류: {message}"
        }


    # -----------------------------------------------------
    # 급식 데이터 확인
    # -----------------------------------------------------

    if "mealServiceDietInfo" not in data:

        return {
            "상태": "없음",
            "메시지": "선택한 날짜의 급식 정보가 없습니다."
        }


    try:

        rows = data["mealServiceDietInfo"][1]["row"]

    except (KeyError, IndexError, TypeError):

        return {
            "상태": "없음",
            "메시지": "선택한 날짜의 급식 정보가 없습니다."
        }


    if not rows:

        return {
            "상태": "없음",
            "메시지": "선택한 날짜의 급식 정보가 없습니다."
        }


    # -----------------------------------------------------
    # 점심 데이터
    # -----------------------------------------------------

    for row in rows:

        if row.get("MMEAL_SC_CODE") == "2":

            메뉴원본 = row.get("DDISH_NM", "")
            칼로리 = row.get("CAL_INFO", "")

            메뉴원본 = 메뉴원본.replace("<br/>", "\n")
            메뉴원본 = 메뉴원본.replace("<br>", "\n")

            메뉴목록 = []

            for 메뉴 in 메뉴원본.split("\n"):

                메뉴 = 메뉴.strip()

                if 메뉴 == "":
                    continue

                메뉴 = 알레르기번호_제거(메뉴)

                메뉴목록.append(메뉴)

            return {
                "상태": "성공",
                "메뉴": 메뉴목록,
                "칼로리": 칼로리
            }


    return {
        "상태": "없음",
        "메시지": "선택한 날짜에는 점심 급식이 없습니다."
    }


